let LANG = (() => {
  try {
    const s = localStorage.getItem("zr_lang");
    if (s && I18N[s]) return s;
  } catch (e) {}
  const n = ((navigator.language || "uz") + "").slice(0, 2).toLowerCase();
  return I18N[n] ? n : "uz";
})();

function t(key, vars) {
  let s = I18N[LANG][key];
  if (s === undefined) s = I18N.uz[key];
  if (s === undefined) return key;
  if (Array.isArray(s) || !vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) =>
    vars[k] !== undefined ? vars[k] : m,
  );
}

function applyI18n() {
  document.documentElement.lang = LANG;
  document.title = t("title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document
    .querySelectorAll(".lang button")
    .forEach((b) => b.classList.toggle("on", b.dataset.lang === LANG));
}
function setLang(l) {
  if (!I18N[l] || l === LANG) return;
  LANG = l;
  try {
    localStorage.setItem("zr_lang", l);
  } catch (e) {}
  applyI18n();
  if (typeof window.onLangChange === "function") window.onLangChange();
}
document.addEventListener("click", (e) => {
  const b = e.target.closest(".lang button");
  if (b) setLang(b.dataset.lang);
});
applyI18n();
